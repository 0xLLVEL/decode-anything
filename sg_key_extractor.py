"""Extract SourceGuardian's fixed Blowfish keys from loader binaries.

The commercial loaders embed a three-entry key table as NUL-terminated
44-byte ASCII strings in read-only data. That table is byte-identical across
every build of a release line, so scanning several binaries and keeping the
majority consensus recovers it without parsing PE section headers.

Keys are printed only as SHA-256 prefixes; the raw values go straight into the
generated module, which is gitignored.

Usage:
    python sg_key_extractor.py loader/*.win
    python sg_key_extractor.py loader/ixed.8.1.win --out sg_keys.py
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from collections import Counter
from pathlib import Path

KEY_LENGTH = 44
CANDIDATE_RE = re.compile(
    rb"(?<![A-Za-z0-9+/=])([A-Za-z0-9+/=]{%d})\x00" % KEY_LENGTH
)

GENERATED_HEADER = '''"""SourceGuardian commercial Blowfish keys.

Generated by sg_key_extractor.py from locally supplied loader binaries.
This module is gitignored and must not be committed or shared.

Each key is used verbatim as a 44-byte ASCII Blowfish key (CBC, IV=0).
"""

from __future__ import annotations

SG_KEYS: tuple[bytes, ...] = (
{keys}
)

SG_KEY_FINGERPRINTS: tuple[str, ...] = (
{fingerprints}
)

# Loaders whose embedded key table matched SG_KEYS exactly.
SG_KEY_AGREEMENT: str = {agreement!r}

SG_KEY_SOURCES: tuple[str, ...] = (
{sources}
)
'''


def fingerprint(key: bytes) -> str:
    return hashlib.sha256(key).hexdigest()[:8]


def scan_binary(path: Path) -> list[tuple[int, bytes]]:
    """Return (offset, key) pairs in file order."""
    data = path.read_bytes()
    return [(match.start(), match.group(1)) for match in CANDIDATE_RE.finditer(data)]


def pick_keys(per_file: dict[Path, list[tuple[int, bytes]]]) -> tuple[list[bytes], str]:
    """Choose the key table by majority agreement across binaries."""
    tables: Counter[tuple[bytes, ...]] = Counter()
    for hits in per_file.values():
        keys = tuple(key for _, key in hits)
        if len(keys) == len({*keys}):
            tables[keys] += 1

    if tables:
        best, votes = tables.most_common(1)[0]
        if votes > 1 or len(per_file) == 1:
            return list(best), f"{votes}/{len(per_file)} loaders agree"

    frequencies: Counter[bytes] = Counter()
    first_offset: dict[bytes, int] = {}
    for hits in per_file.values():
        for offset, key in hits:
            frequencies[key] += 1
            first_offset.setdefault(key, offset)

    if len(frequencies) < 3:
        raise SystemExit(
            f"only {len(frequencies)} candidate key(s) found; need at least 3"
        )

    ordered = sorted(frequencies.items(), key=lambda item: (-item[1], first_offset[item[0]]))
    keys = [key for key, _ in ordered[:3]]
    seen = sum(1 for hits in per_file.values() if {key for _, key in hits} >= set(keys))
    return keys, f"frequency fallback, {seen}/{len(per_file)} loaders agree"


def render_module(keys: list[bytes], agreement: str, sources: list[str]) -> str:
    key_lines = "".join(f"    {key!r},\n" for key in keys)
    fingerprint_lines = "".join(f'    "{fingerprint(key)}",\n' for key in keys)
    source_lines = "".join(f"    {name!r},\n" for name in sources)
    return GENERATED_HEADER.format(
        keys=key_lines,
        fingerprints=fingerprint_lines,
        agreement=agreement,
        sources=source_lines,
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Extract SourceGuardian's fixed Blowfish keys from loader binaries.",
    )
    parser.add_argument(
        "loaders",
        nargs="+",
        type=Path,
        help="Loader binaries to scan (ixed.*.win / .lin / .dar)",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=Path("sg_keys.py"),
        help="Generated key module (default: sg_keys.py, gitignored)",
    )
    args = parser.parse_args(argv)

    missing = [path for path in args.loaders if not path.is_file()]
    if missing:
        for path in missing:
            print(f"[-] not found: {path}", file=sys.stderr)
        return 2

    per_file = {path: scan_binary(path) for path in args.loaders}
    for path, hits in per_file.items():
        offsets = ", ".join(hex(offset) for offset, _ in hits)
        prints = ", ".join(fingerprint(key) for _, key in hits)
        print(f"[*] {path.name}: {len(hits)} candidate(s) at {offsets} [{prints}]")

    keys, agreement = pick_keys(per_file)
    key_set = set(keys)
    sources = sorted(
        path.name for path, hits in per_file.items() if {key for _, key in hits} >= key_set
    )

    args.out.write_text(render_module(keys, agreement, sources), encoding="utf-8")

    print(f"[+] {len(keys)} keys written to {args.out} ({agreement})")
    for index, key in enumerate(keys):
        prefix = "KEY%d" % index
        print(f"    {prefix}: sha256[:8]={fingerprint(key)} length={len(key)}")
    print(f"[+] matched by {len(sources)}/{len(per_file)} loader(s)")
    print("[!] keep this file local; it is listed in .gitignore")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
